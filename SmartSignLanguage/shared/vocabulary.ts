// Vocabulary types
export type Category =
  | "greeting"
  | "action-verbs"
  | "family"
  | "animals"
  | "colors"
  | "body-health"
  | "deaf-community-asl"
  | "nature-weather"
  | "time-calendar"
  | "sports-activities"
  | "education-school"
  | "emotions-feelings"
  | "food-drink"
  | "places-buildings"
  | "travel-transportation"
  | "technology-computer";

export type Difficulty = "beginner" | "intermediate" | "advanced";

import { driveVideoMap } from "./google-drive";

export interface VocabularyCard {
  id: string;
  word: string;
  category: Category;
  difficulty: Difficulty;
  videoUrl: string;
  description: string;
  example?: string;
}

// SRS (Spaced Repetition System) types
export interface SRSProgress {
  cardId: string;
  userId: string;
  status: "new" | "learning" | "mastered";
  interval: number; // days until next review
  difficulty: number; // 1-5, how hard to remember
  easeFactor: number; // SM-2 algorithm ease factor
  nextReviewDate: string; // ISO date
  attempts: number;
  correctAttempts: number;
  lastReviewedDate?: string;
  createdAt: string;
  updatedAt: string;
}

export interface LearningProgress {
  cardId: string;
  status: "new" | "learning" | "mastered";
  attempts: number;
  lastReviewed?: Date;
}

// Quiz types
export interface QuizQuestion {
  id: string;
  type:
    | "video-to-text"
    | "text-to-video"
    | "multiple-choice"
    | "meaning_quiz"
    | "video_to_word"
    | "word_to_sign"
    | "common_mistake";
  cardId: string;
  question: string;
  options: string[];
  correctAnswerIndex: number;
  difficulty: Difficulty;
  explanation?: string;
}

export interface QuizResult {
  id: string;
  userId: string;
  cardIds: string[];
  questions: QuizQuestion[];
  answers: number[];
  score: number;
  totalQuestions: number;
  completedAt: string;
  difficulty: Difficulty;
}

// Achievement types
export interface Achievement {
  id: string;
  name: string;
  description: string;
  icon: string;
  type: "milestone" | "streak" | "quiz" | "collection";
  requirement: number;
  earned: boolean;
  unlockedDate?: string;
}

// Helper: build videoUrl from driveVideoMap key
function driveUrl(key: string): string {
  const entry = driveVideoMap[key];
  if (!entry) throw new Error(`driveVideoMap missing key: "${key}"`);
  return `/api/video-stream/${key}`;
}

